import { CircleSlash, RadioTower } from 'lucide-react'

/**
 * Persistent, unmissable banner distinguishing demo data from real hardware.
 */
export function SourceBanner({ demo }: { demo: boolean }) {
  if (demo) {
    return (
      <div
        className="flex items-start gap-3 rounded-xl border border-amber-400/35 bg-amber-400/10 px-4 py-3"
        role="status"
      >
        <CircleSlash className="mt-0.5 h-5 w-5 shrink-0 text-amber-400" aria-hidden />
        <div>
          <p className="text-sm font-bold tracking-wide text-amber-400">DEMO DATA — NOT CONNECTED TO HARDWARE</p>
          <p className="mt-0.5 text-xs leading-relaxed text-lavender/85">
            All measurements below are generated by a labelled simulation model for interface development and
            demonstration. They are not readings from a real battery.
          </p>
        </div>
      </div>
    )
  }
  return (
    <div className="flex items-start gap-3 rounded-xl border border-sea-400/35 bg-sea-400/10 px-4 py-3" role="status">
      <RadioTower className="mt-0.5 h-5 w-5 shrink-0 text-sea-400" aria-hidden />
      <div>
        <p className="text-sm font-bold tracking-wide text-sea-300">HARDWARE CONNECTED</p>
        <p className="mt-0.5 text-xs leading-relaxed text-lavender/85">
          The interface animates workflow state only. Charts populate exclusively from validated device readings —
          no simulated values are mixed in, and missing samples stay empty.
        </p>
      </div>
    </div>
  )
}
